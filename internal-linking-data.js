export function findReviewByItem(item) {
  if (!item) return null;
  if (item.asin && ASIN_TO_REVIEW_SLUG[item.asin]) {
    return REVIEWS_BY_SLUG[ASIN_TO_REVIEW_SLUG[item.asin]] || null;
  }
  const name = (item.name || item.productName || item.title || '').toLowerCase();
  for (const slug in REVIEWS_BY_SLUG) {
    const rev = REVIEWS_BY_SLUG[slug];
    const rTitle = rev.title.toLowerCase();
    const rModel = rev.model.toLowerCase();
    if (name.includes(rModel) || (rev.asin && name.includes(rev.asin.toLowerCase()))) {
      return rev;
    }
  }
  return null;
}

export function getRelatedReviewsForGuide(guideSlug) {
  const matches = GUIDE_TO_REVIEWS[guideSlug] || [];
  return matches.map(m => {
    const rev = REVIEWS_BY_SLUG[m.reviewSlug];
    return rev ? { ...rev, contextNote: m.contextNote } : null;
  }).filter(Boolean);
}

export function getRelatedGuidesForReview(reviewSlug) {
  const matches = REVIEW_TO_GUIDES[reviewSlug] || [];
  return matches.map(m => {
    const guide = GUIDES_BY_SLUG[m.guideSlug];
    return guide ? { ...guide, contextNote: m.contextNote } : null;
  }).filter(Boolean);
}

export function getCompetingReviews(reviewSlug) {
  const current = REVIEWS_BY_SLUG[reviewSlug];
  if (!current) return [];
  return Object.values(REVIEWS_BY_SLUG)
    .filter(r => r.slug !== reviewSlug && (r.category === current.category || r.brand === current.brand || r.price === current.price))
    .slice(0, 3);
}
